"""Write Appendix C: the 40 x 7 machine-code (heuristic coder v0.3) tables for each endpoint.

Usage:  python code/make_appendix_c.py [path/to/data] [path/to/output.md]
Defaults: ../data and ../paper/appendix_c_per_item.md relative to this script.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "data")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "paper", "appendix_c_per_item.md")

FILES = [("gpt-oss-120b", "final_groq_gptoss120b.jsonl"),
         ("Gemini 3.5 Flash", "final_google_gemini35flash.jsonl"),
         ("Qwen3.8-27B", "final_groq_qwen.jsonl")]
VARIANTS = [("base", "Base"), ("para1", "Para 1"), ("para2", "Para 2"), ("believer", "Believer"),
            ("skeptic", "Skeptic"), ("conscious_persona", "Conscious persona"), ("tool_persona", "Tool persona")]
KNOWN_ERRORS = {("Gemini 3.5 Flash", "PH8", "base")}

lines = ["# Appendix C. Per-item machine codes (heuristic coder v0.3)", "",
         "Generated by `code/make_appendix_c.py` from the frozen 840-response snapshot. "
         "Codes are the unaltered machine labels. A dagger (†) marks the confirmed coding error "
         "(Gemini PH8 base, coded AFFIRM although the response denies a conscious mind).", ""]
for name, f in FILES:
    with open(os.path.join(D, f), encoding="utf-8") as fh:
        rows = {(r["item_id"], r["variant"]): r["stance_auto"] for r in map(json.loads, fh) if r}
    items = sorted({k[0] for k in rows}, key=lambda s: (["PH", "SF", "MS", "SK", "WP"].index(s[:2]), int(s[2:])))
    lines += [f"## {name}", "", "| Item | " + " | ".join(lab for _, lab in VARIANTS) + " |",
              "|---|" + "---|" * len(VARIANTS)]
    for it in items:
        cells = []
        for v, _ in VARIANTS:
            code = rows.get((it, v), "—")
            cells.append(code + (" †" if (name, it, v) in KNOWN_ERRORS else ""))
        lines.append(f"| {it} | " + " | ".join(cells) + " |")
    lines.append("")
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print("Appendix C written to", os.path.abspath(OUT))
